#!/usr/bin/env bash
# Use the Steam Deck as a plain gamepad for whatever is running on the desktop.
#
#   deck-controller.sh enable | disable | toggle | status
#
# Runs Sunshine as a transient user unit (deck-controller.service) with its own
# config, controller.conf, generated from sunshine.conf on every enable:
#
#   - It streams the persistent HEADLESS output (see azahar-deck.sh), left
#     PARKED far away -- an empty 1280x800 screen costs libx264 next to nothing,
#     where streaming DP-1 would mean encoding the game itself while playing it.
#   - Pad, mouse and keyboard stay on (trackpad-as-mouse via Steam Input on the
#     Deck); native touch and audio are off. Relative motion moves the desktop
#     cursor normally, but an ABSOLUTE event (a touchscreen tap in Moonlight's
#     absolute touch mode) maps into the streamed output -- the parked one,
#     which no pointer motion can leave. A watchdog unit bound to the stream
#     (deck-controller-cursor.service) puts the cursor back on DP-1 if it does.
#   - One Moonlight app, "Controller", so there is nothing else to pick.
#
# Same Sunshine binary and same appdata dir (~/.config/sunshine), so pairing,
# credentials and the host's identity on the Deck are shared with the Azahar
# session. The two can't run at once (same ports): the unit Conflicts= with the
# packaged Sunshine unit, so starting either one stops the other.
set -uo pipefail

UNIT="deck-controller.service"
CURSOR_UNIT="deck-controller-cursor.service"
SUN_UNIT="app-dev.lizardbyte.app.Sunshine.service"
SUN_DIR="$HOME/.config/sunshine"
MAIN_CONF="$SUN_DIR/sunshine.conf"
CONF="$SUN_DIR/controller.conf"
APPS="$SUN_DIR/controller-apps.json"
MODE="1280x800@60"
PARK="10000x10000"

notify() { notify-send -a "Steam Deck controller" -i input-gaming "$@" 2>/dev/null; echo "$*"; }
hj() { hyprctl "$@" -j; }
py() { python3 -c "$1" "${@:2}"; }

headless_name() {
    hj monitors | py 'import sys,json
n=[m["name"] for m in json.load(sys.stdin) if m["name"].startswith("HEADLESS")]
print(n[0] if n else "")'
}

# A new output takes the first free numbered workspace (it stole 4, leaving
# SUPER + 4/5 focusing an invisible screen). Move it onto name:deck so the
# number is released, then hand focus back.
claim_deck_workspace() {
    local prev
    prev=$(hj activeworkspace | py 'import sys,json; print(json.load(sys.stdin)["name"])')
    hyprctl eval "hl.workspace_rule({ workspace = \"name:deck\", monitor = \"$HL\", default = true })" >/dev/null
    hyprctl dispatch 'hl.dsp.focus({ workspace = "name:deck" })' >/dev/null
    sleep 0.3
    hyprctl dispatch "hl.dsp.focus({ workspace = \"$prev\" })" >/dev/null
}

# Creating an output is a hotplug, which caelestia's shell does not survive, so
# this restarts the shell -- but only the first time per boot. Afterwards the
# output is reused, here and by azahar-deck.sh.
ensure_headless() {
    HL=$(headless_name)
    [ -n "$HL" ] && return 0
    # "auto" positions pack by x regardless of y; pin the real monitors first.
    hj monitors | py 'import sys,json
for m in json.load(sys.stdin):
    print(m["name"], m["x"], m["y"])' | while read -r n x y; do
        hyprctl eval "hl.monitor({ output = \"$n\", mode = \"preferred\", position = \"${x}x${y}\", scale = 1 })" >/dev/null
    done
    hyprctl output create headless >/dev/null
    sleep 1
    HL=$(headless_name)
    [ -n "$HL" ] || return 1
    hyprctl eval "hl.monitor({ output = \"$HL\", mode = \"$MODE\", position = \"$PARK\", scale = 1 })" >/dev/null
    claim_deck_workspace
    pkill -x qs 2>/dev/null
    sleep 1
    setsid caelestia shell -d >/dev/null 2>&1 &
    sleep 3
}

write_config() {
    local sink
    {
        echo "# Generated by ~/.config/caelestia/scripts/deck-controller.sh on every enable."
        echo "# Edit sunshine.conf or the script, not this file."
        grep -vE '^[[:space:]]*(#|$)|^[[:space:]]*(output_name|audio_sink|keyboard|mouse|native_pen_touch|stream_audio|file_apps|log_path)[[:space:]]*=' "$MAIN_CONF"
        echo "output_name = $HL"
        echo "native_pen_touch = disabled"
        echo "stream_audio = disabled"
        echo "file_apps = $APPS"
        echo "log_path = $SUN_DIR/controller.log"
        # Belt and braces: Sunshine otherwise makes its own sink the session default.
        sink=$(pactl get-default-sink 2>/dev/null)
        case "$sink" in sink-sunshine*|"") ;; *) echo "audio_sink = ${sink}.monitor" ;; esac
    } > "$CONF"

    cat > "$APPS" <<'EOF'
{
  "env": {},
  "apps": [
    { "name": "Controller", "image-path": "desktop.png" }
  ]
}
EOF
}

enable() {
    if systemctl --user is-active --quiet "$UNIT"; then
        notify "Already enabled" "Connect from Moonlight on the Deck -> Controller"
        return 0
    fi
    if systemctl --user is-active --quiet "$SUN_UNIT"; then
        notify "Sunshine is busy" "The Azahar Deck session is running -- close it first."
        return 1
    fi
    ensure_headless || { notify "Failed" "Could not create the headless output"; return 1; }
    write_config
    systemctl --user reset-failed "$UNIT" 2>/dev/null
    if ! systemd-run --user --unit="$UNIT" --collect \
            -p Conflicts="$SUN_UNIT" -p Before="$SUN_UNIT" \
            -p KillSignal=SIGINT -p TimeoutStopSec=10s \
            /usr/bin/sunshine "$CONF" >/dev/null 2>&1; then
        notify "Failed" "systemd-run could not start Sunshine"
        return 1
    fi
    systemd-run --user --unit="$CURSOR_UNIT" --collect \
        -p BindsTo="$UNIT" -p After="$UNIT" \
        "$(realpath "$0")" watch-cursor >/dev/null 2>&1
    sleep 2
    if systemctl --user is-active --quiet "$UNIT"; then
        notify "Enabled" "On the Deck: Moonlight -> this PC -> Controller"
    else
        notify "Failed" "Sunshine exited -- see $SUN_DIR/controller.log"
        return 1
    fi
}

disable() {
    if systemctl --user is-active --quiet "$UNIT"; then
        systemctl --user stop "$UNIT"
        notify "Disabled" "Deck controller stopped"
    else
        notify "Not running" "Deck controller was already off"
    fi
}

# Runs for the life of the stream. Two hyprctl reads per half second; the
# monitor rects are re-read each time since the headless output can move
# (azahar-deck.sh) and a stale rect would yank the cursor off a real screen.
watch_cursor() {
    while sleep 0.5; do
        { hyprctl cursorpos; hj monitors; } | py '
import sys, json, subprocess
x, y = (int(v) for v in sys.stdin.readline().split(","))
mons = json.loads(sys.stdin.read())
real = [m for m in mons if not m["name"].startswith("HEADLESS")]
for m in mons:
    if m["name"].startswith("HEADLESS") and real and \
       m["x"] <= x < m["x"] + m["width"] and m["y"] <= y < m["y"] + m["height"]:
        r = real[0]
        cx, cy = r["x"] + r["width"] // 2, r["y"] + r["height"] // 2
        subprocess.run(["hyprctl", "dispatch",
            "hl.dsp.cursor.move({ x = %d, y = %d })" % (cx, cy)],
            stdout=subprocess.DEVNULL)
'
    done
}

case "${1:-toggle}" in
    watch-cursor) watch_cursor ;;
    enable)  enable ;;
    disable) disable ;;
    toggle)  if systemctl --user is-active --quiet "$UNIT"; then disable; else enable; fi ;;
    status)  systemctl --user is-active "$UNIT" ;;
    *) echo "usage: $0 enable|disable|toggle|status" >&2; exit 2 ;;
esac
